    // Mutation caught: use decrypted actor/target topics without binding them to authenticated outer
    // install IDs, allowing a valid peer signature to relay a payload for another actor or target.
    @Test
    fun inboxRejectsActorOrTargetThatDoesNotBindToTheAuthenticatedOuterContext() {
        val actorMismatch = inboundEnvelope(
            messageId = "TEST-ONLY-actor-mismatch",
            payload = inboundPayload(EVENT_ID).put("actorTopic", "TEST-ONLY-someone-else")
        )
        val targetMismatch = inboundEnvelope(
            messageId = "TEST-ONLY-target-mismatch",
            payload = inboundPayload(EVENT_ID_B).put("targetTopic", "TEST-ONLY-someone-else")
        )
        http.inboxEnvelopes = listOf(actorMismatch, targetMismatch)

        assertTrue(recipient.inbox(recipientApi).reconcile())

        assertFalse(EventStore.contains(recipient.context, EVENT_ID))
        assertFalse(EventStore.contains(recipient.context, EVENT_ID_B))
        assertEquals(setOf("rejected"), http.terminalAcks.map { it.outcome }.toSet())
    }

