/**
 * RED contract for Task 12's encrypted relay transport.
 *
 * Intended minimal API (all storage is device-local):
 * - RelayApi(httpsBaseUrl, installCredential, RelayApiHttp) fails closed for non-HTTPS bases,
 *   validates/redacts the authenticated HTTP boundary, and exposes routes(), enqueue(envelope),
 *   inbox(), and acknowledge(terminalAcks).
 * - RelayOutbox(context, localInstallId, RelayCrypto, RelayPeerStore, RelayApi) materializes one
 *   durable RelayOutboundEnvelope per trusted route, then flushes the durable records without
 *   regenerating message IDs or ciphertext after a transport failure.
 * - RelayInbox(context, localInstallId, RelayCrypto, RelayPeerStore, RelayApi, RelayInboxFaults)
 *   processes a non-destructive inbox to durable terminal outcomes before batching ACKs.
 * - RelaySyncTransport(outbox, inbox) is injectable but SyncTransportRuntime remains ntfy until
 *   Task 16's atomic cutover. RelayApiHttp is the only HTTP double; RelayInboxFaults is the only
 *   fault-injection seam.
 *
 * Fixture identities are generated by the real RelayIdentityStore and envelopes by real
 * RelayCrypto. Assertions intentionally inspect no key material, credential, or plaintext payload.
 */
