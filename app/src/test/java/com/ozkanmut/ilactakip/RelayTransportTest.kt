    // Mutation caught: create ciphertext only in memory, regenerate it/message ID after failure,
    // or mark its source event synced before the relay has accepted every materialized recipient.
    @Test
    fun offlineSenderPersistsOneRecipientEnvelopeAndRetriesTheSameRecordAfterReconstruction() {
        val event = localEvent(EVENT_ID)
        EventStore.append(sender.context, event)
        assertTrue(sender.peers.pin(recipient.installId, recipient.identity))
        http.routes = listOf(route(ROUTE_ID, recipient))
        http.enqueueFailure = IOException("TEST-ONLY offline")
        val firstOutbox = sender.outbox(senderApi)

        assertFalse(firstOutbox.flush())
        val persisted = firstOutbox.recordsFor(EVENT_ID).single()
        assertEquals("pending", EventStore.load(sender.context).single { it.eventId == EVENT_ID }.syncState)

        http.enqueueFailure = null
        val reconstructed = sender.outbox(senderApi)
        assertTrue(reconstructed.flush())

        val accepted = http.acceptedEnvelopes.single()
        assertEquals(persisted.outerContext.messageId, accepted.outerContext.messageId)
        assertArrayEquals(persisted.ciphertext, accepted.ciphertext)
        assertEquals("synced", EventStore.load(sender.context).single { it.eventId == EVENT_ID }.syncState)
        assertTrue(reconstructed.recordsFor(EVENT_ID).isEmpty())
    }

    // Mutation caught: encrypt once for multiple routes, trust a server key, or omit route/key data
    // from the sealed outer context.
    @Test
    fun outboxEncryptsIndependentlyPerPinnedRecipientAndRejectsServerKeySubstitution() {
        val otherRecipient = device("TEST-ONLY-recipient-b")
        val event = localEvent(EVENT_ID).copy(targetTopic = "")
        EventStore.append(sender.context, event)
        sender.peers.pin(recipient.installId, recipient.identity)
        sender.peers.pin(otherRecipient.installId, otherRecipient.identity)
        http.routes = listOf(route(ROUTE_ID, recipient), route(ROUTE_ID_B, otherRecipient))

        val outbox = sender.outbox(senderApi)
        assertEquals(2, outbox.materializePending())
        val records = outbox.recordsFor(EVENT_ID)

        assertEquals(setOf(ROUTE_ID, ROUTE_ID_B), records.map { it.outerContext.routeId }.toSet())
        assertEquals(setOf(recipient.installId, otherRecipient.installId),
            records.map { it.outerContext.recipientInstallId }.toSet())
        assertFalse(records[0].ciphertext.contentEquals(records[1].ciphertext))

        EventStore.append(sender.context, localEvent(EVENT_SUBSTITUTION_ID))
        http.routes = listOf(route(ROUTE_ID, recipient).copy(recipientIdentity = otherRecipient.identity))
        assertEquals(0, outbox.materializePending())
        assertTrue(outbox.recordsFor(EVENT_SUBSTITUTION_ID).isEmpty())
    }

